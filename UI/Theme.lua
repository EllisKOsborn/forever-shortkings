-- White washes (alpha), never a new hue.
Theme.WASH = { hairline = 0.10, hover = 0.06, selected = 0.09, pressed = 0.12, zebra = 0.02, strong = 0.20 }

Theme.SPACE = { 4, 8, 12, 16, 24, 32 }
Theme.TYPE = { hero = 26, display = 18, title = 15, body = 13, label = 12, small = 11 }

-- Contrast floors (docs/DESIGN.md section 13).
Theme.FLOORS = { primary = 7.0, other = 4.5 }

-- Glyph textures generated by docs/design/icons.js (32x32 white, tinted here).
Theme.ICON_PATH = "Interface\\AddOns\\ShortKings\\Media\\Icons\\"
Theme.ICONS = {
	overview = true, roster = true, character = true, crafters = true, settings = true, raids = true,
	professions = true, close = true, search = true, chevron = true, chevronUp = true, chevronLeft = true, copy = true,
	inbox = true, whisper = true, refresh = true, statusHollow = true,
}
Theme.WHITE = "Interface\\Buttons\\WHITE8X8"
Theme.EMBLEM = "Interface\\Icons\\INV_Misc_Bomb_04" -- the game's dynamite icon

function Theme.Icon(name)
	assert(Theme.ICONS[name], "unknown icon " .. tostring(name))
	return Theme.ICON_PATH .. name .. ".tga"
end

-- Token name (new or legacy) or a raw "RRGGBB" -> hex.
function Theme.Hex(name)
	return Theme.HEX[name] or Theme.HEX[Theme.LEGACY[name] or ""] or name
end

local cache = {}
function Theme.RGB(name)
	local c = cache[name]
	if not c then
		local hex = Theme.Hex(name)
		c = { tonumber(hex:sub(1, 2), 16) / 255, tonumber(hex:sub(3, 4), 16) / 255, tonumber(hex:sub(5, 6), 16) / 255 }
		cache[name] = c
	end
	return c[1], c[2], c[3]
end

-- "|cffRRGGBB" escape for inline coloured text.
function Theme.Code(name)
	return "|cff" .. Theme.Hex(name)
end

function Theme.Color(name, alpha)
	local r, g, b = Theme.RGB(name)
	return CreateColor(r, g, b, alpha or 1)
end

---------------------------------------------------------------------------
-- Contrast (WCAG relative luminance). Pure; tested against the floors.
---------------------------------------------------------------------------
local function lin(v) return v <= 0.03928 and v / 12.92 or ((v + 0.055) / 1.055) ^ 2.4 end
local function lum(r, g, b) return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b) end

-- Colour `name` with a white wash of `alpha` on top, as r, g, b.
function Theme.Washed(name, alpha)
	local r, g, b = Theme.RGB(name)
	return r + (1 - r) * alpha, g + (1 - g) * alpha, b + (1 - b) * alpha
end

-- Ratio between two colours given as token names or {r, g, b}.
function Theme.Contrast(a, b)
	local ra, ga, ba
	if type(a) == "table" then ra, ga, ba = a[1], a[2], a[3] else ra, ga, ba = Theme.RGB(a) end
	local rb, gb, bb
	if type(b) == "table" then rb, gb, bb = b[1], b[2], b[3] else rb, gb, bb = Theme.RGB(b) end
	local x, y = lum(ra, ga, ba), lum(rb, gb, bb)
	return (math.max(x, y) + 0.05) / (math.min(x, y) + 0.05)
end

---------------------------------------------------------------------------
-- Painting textures
---------------------------------------------------------------------------
function Theme.Solid(tex, name, alpha)
	local r, g, b = Theme.RGB(name)
	tex:SetColorTexture(r, g, b, alpha or 1)
end

-- White wash (hover, selected, hairline …) at the alpha of Theme.WASH[kind].
function Theme.Wash(tex, kind)
	tex:SetColorTexture(1, 1, 1, Theme.WASH[kind] or kind)
end

-- Two-colour gradient. `from` is the bottom (VERTICAL) or left (HORIZONTAL).
function Theme.Gradient(tex, orientation, from, to, alphaFrom, alphaTo)
	tex:SetColorTexture(1, 1, 1, 1)
	tex:SetGradient(orientation, Theme.Color(from, alphaFrom), Theme.Color(to, alphaTo))
end

-- A glyph texture tinted with a token.
function Theme.Glyph(parent, name, size, color, layer)
	local t = parent:CreateTexture(nil, layer or "ARTWORK")
	t:SetTexture(Theme.Icon(name))
	t:SetSize(size, size)
	t:SetVertexColor(Theme.RGB(color or "textDim"))
	return t
end

-- Inline glyph for FontStrings (tinted). size in px.
function Theme.InlineIcon(name, size, color)
	local r, g, b = Theme.RGB(color or "textDim")
	return string.format("|T%s:%d:%d:0:0:32:32:0:32:0:32:%d:%d:%d|t", Theme.Icon(name), size, size,
		r * 255, g * 255, b * 255)
end

---------------------------------------------------------------------------
-- Hairlines: 1 physical pixel, white at 10% (or a token colour).
---------------------------------------------------------------------------
local function line(frame, layer, sub)
	local t = frame:CreateTexture(nil, layer or "BORDER", nil, sub or 1)
	SK.Compat.NoSnap(t)
	return t
end

local function paintLines(lines, color, alpha)
	for _, t in ipairs(lines) do
		if color then Theme.Solid(t, color, alpha) else Theme.Wash(t, alpha or "hairline") end
	end
end

-- Outline the whole frame. frame.border = { top, bottom, left, right }.
function Theme.Hairline(frame, color, alpha)
	local t = { line(frame), line(frame), line(frame), line(frame) }
	t[1]:SetPoint("TOPLEFT"); t[1]:SetPoint("TOPRIGHT"); SK.Compat.PixelHeight(t[1], 1)
	t[2]:SetPoint("BOTTOMLEFT"); t[2]:SetPoint("BOTTOMRIGHT"); SK.Compat.PixelHeight(t[2], 1)
	t[3]:SetPoint("TOPLEFT"); t[3]:SetPoint("BOTTOMLEFT"); SK.Compat.PixelWidth(t[3], 1)
	t[4]:SetPoint("TOPRIGHT"); t[4]:SetPoint("BOTTOMRIGHT"); SK.Compat.PixelWidth(t[4], 1)
	frame.border = t
	paintLines(t, color, alpha)
	return t
end

-- One edge: "TOP", "BOTTOM", "LEFT" or "RIGHT".
function Theme.Edge(frame, side, color, alpha)
	local t = line(frame, "ARTWORK", 7)
	if side == "TOP" or side == "BOTTOM" then
		t:SetPoint(side .. "LEFT"); t:SetPoint(side .. "RIGHT"); SK.Compat.PixelHeight(t, 1)
	else
		t:SetPoint("TOP" .. side); t:SetPoint("BOTTOM" .. side); SK.Compat.PixelWidth(t, 1)
	end
	paintLines({ t }, color, alpha)
	return t
end

-- Legacy name: every border is a hairline now (thickness is ignored).
function Theme.Border(frame)
	return Theme.Hairline(frame)
end

-- Recolour an outline: a token, or nil for the plain hairline.
function Theme.SetBorderColor(frame, name, alpha)
	if not frame.border then return end
	if name == nil or name == "leather" then paintLines(frame.border, nil, alpha)
	else paintLines(frame.border, name, alpha or 1) end
end

-- Flat ground plus hairline. opts = { tone = "panel", border = true }.
-- Legacy opts (from/to/thickness/gold) are accepted and ignored.
function Theme.Panel(frame, opts)
	opts = opts or {}
	local bg = frame:CreateTexture(nil, "BACKGROUND", nil, -7) -- above Theme.Shadow (-8)
	bg:SetAllPoints()
	Theme.Solid(bg, opts.tone or "bg")
	frame.bg = bg
	if opts.border ~= false then Theme.Hairline(frame) end
	return frame
end

-- The window's soft shadow: four stacked translucent rectangles behind it
-- (no image file). Only windows get one.
function Theme.Shadow(frame)
	local alphas = { 0.20, 0.13, 0.08, 0.04 }
	for i, a in ipairs(alphas) do
		local t = frame:CreateTexture(nil, "BACKGROUND", nil, -8)
		t:SetColorTexture(0.02, 0, 0.01, a)
		t:SetPoint("TOPLEFT", -i * 3, i * 2)
		t:SetPoint("BOTTOMRIGHT", i * 3, -i * 4)
	end
end

---------------------------------------------------------------------------
-- Text
---------------------------------------------------------------------------
-- size: px or a Theme.TYPE name ("body", "label" …).
function Theme.Font(fs, size, color, flags)
	local font = (GameFontNormal and GameFontNormal:GetFont()) or STANDARD_TEXT_FONT
	fs:SetFont(font, Theme.TYPE[size] or size or Theme.TYPE.body, flags or "")
	if color then fs:SetTextColor(Theme.RGB(color)) end
	fs:SetShadowOffset(1, -1)
	fs:SetShadowColor(0, 0, 0, 0.8)
	return fs
end

function Theme.Text(parent, size, color, layer)
	local fs = parent:CreateFontString(nil, layer or "OVERLAY")
	Theme.Font(fs, size, color or "text")
	return fs
end

-- Section heading: label size, textDim, upper case (the game font has no
-- letter spacing, so the capitals do that job).
function Theme.Heading(parent, text)
	local fs = Theme.Text(parent, "label", "textDim")
	fs:SetText(string.upper(text))
	return fs
end

function Theme.ClassText(name, classFile)
	local r, g, b = SK.Compat.ClassColor(classFile)
	return string.format("|cff%02x%02x%02x%s|r", r * 255, g * 255, b * 255, name or "?")
end

---------------------------------------------------------------------------
-- Status marks: shape AND colour (never colour alone), as inline textures.
--   addon   filled 8 px square, success
--   online  hollow 8 px square, warning (online without the addon)
--   offline 8 x 2 dash, textMuted
---------------------------------------------------------------------------
local function tint(name)
	local r, g, b = Theme.RGB(name)
	return math.floor(r * 255 + 0.5), math.floor(g * 255 + 0.5), math.floor(b * 255 + 0.5)
end

Theme.STATUS_MARK = {
	addon = string.format("|T%s:8:8:0:0:8:8:0:8:0:8:%d:%d:%d|t", Theme.WHITE, tint("success")),
	online = string.format("|T%sstatusHollow.tga:8:8:0:0:32:32:0:32:0:32:%d:%d:%d|t", Theme.ICON_PATH, tint("warning")),
	offline = string.format("|T%s:2:8:0:0:8:8:0:8:0:8:%d:%d:%d|t", Theme.WHITE, tint("textMuted")),
}

function Theme.StatusMark(status)
	return Theme.STATUS_MARK[status] or Theme.STATUS_MARK.offline
end

---------------------------------------------------------------------------
-- Time helpers
---------------------------------------------------------------------------
Theme.STALE_AFTER = 7 * 86400 -- data older than this is labelled "may be out of date"

function Theme.IsStale(ts, now)
	return ts ~= nil and (now or SK.Compat.Now()) - ts > Theme.STALE_AFTER
end

-- "now", "5m", "3h", "2d"
function Theme.Ago(ts, now)
	if not ts then return "never" end
	now = now or SK.Compat.Now()
	local d = now - ts
	if d < 120 then return "now" end
	if d < 3600 then return math.floor(d / 60) .. "m" end
	if d < 86400 then return math.floor(d / 3600) .. "h" end
	return math.floor(d / 86400) .. "d"
end

---------------------------------------------------------------------------
-- Motion (docs/DESIGN.md section 15). Fades only; nothing when the player
-- turned on Reduce motion.
---------------------------------------------------------------------------
function Theme.ReduceMotion()
	return SK.DB ~= nil and SK.DB.settings ~= nil and SK.DB.settings.reduceMotion == true
end

-- Fade `frame` in over `seconds` (default 0.12). Returns true if it animated.
function Theme.FadeIn(frame, seconds)
	if Theme.ReduceMotion() or not frame.CreateAnimationGroup then
		frame:SetAlpha(1)
		return false
	end
	local ag = rawget(frame, "skFade")
	if not ag then
		ag = frame:CreateAnimationGroup()
		local a = ag:CreateAnimation("Alpha")
		a:SetFromAlpha(0)
		a:SetToAlpha(1)
		a:SetSmoothing("OUT")
		ag.alpha = a
		frame.skFade = ag
	end
	ag.alpha:SetDuration(seconds or 0.12)
	ag:Stop()
	ag:Play()
	return true
end
