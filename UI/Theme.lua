-- Theme: the Short Kings design system in code (docs/DESIGN.md).
-- Plum and pink, one accent, depth by tone, 1 px hairlines, square corners.
-- Colours, washes, sizes and the glyph textures live here; widgets and tabs
-- only ask for them by name. Values must match docs/design/tokens.json
-- (a test checks it).
local _, SK = ...

local Theme = {}
SK.Theme = Theme

